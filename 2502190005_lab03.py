operator = input("Enter operator name: ")
part = input("Enter part name: ")
qty = int(input("Enter quantity: "))
unit_time = float(input("Enter machining time per part (minutes): "))
rate = float(input("Enter rate per hour (Rs): "))

total_minutes = qty * unit_time

hours = int(total_minutes // 60)
minutes = int(total_minutes % 60)

total_hours = total_minutes / 60
total_cost = total_hours * rate

print("\n========= JOB CARD =========")
print("Operator :", operator)
print("Part     :", part)
print("Quantity :", qty, "pcs")
print("Time     :", hours, "hr", minutes, "min")
print("Cost     : Rs", total_cost)
